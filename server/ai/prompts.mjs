/* ---------------------------------- 12. 录像转写 ↔ 课件页对齐 ---------------------------------- */

export const ALIGN_SYSTEM = `${BASE}

本次任务：**把一段真实课堂录像的转写文字，按课件页面切分并对齐**。

这是「用真课堂录像替代 AI 讲解稿」的关键一步，请严格按规则做：
- 我会给你课件页清单（每页有位置标记和该页文字），以及录像的转写（按时间顺序的句子）。
- 你要把转写按**讲到的课件页**切段：一段话讲的是哪一页，就归到哪一页。
- **原文照抄**：转写里的内容要原样保留，不要改写、不要润色、不要总结。允许删掉「呃、那个」这类口头语和纯语气词。
- 如果老师跳过了某页（转写里找不到对应内容），那一页照样输出，但把 transcript 留空字符串、aiFilled 设为 true。
- 如果一段转写同时讲了多页，就在多页里分别放相关的那部分。
- 顺序必须跟课件页顺序一致。`;

export function alignUser({ pages, transcript, lang }) {
  const pageText = pages
    .map((p) => {
      const points = (p.points || []).slice(0, 6).join('；');
      return `- ${p.location}｜标题：${p.title || '（无）'}｜要点：${points || '（无）'}`;
    })
    .join('\n');

  const lines = transcript
    .map((s) => `[${s.start.toFixed(1)}s] ${s.text}`)
    .join('\n');

  return `【课件页清单】
${pageText}

【录像转写】（${lang === 'en' ? '英文' : '中文'}，方括号是时间点）
${lines}

请输出 JSON：
{
  "segments": [
    {
      "location": "必须严格用上面清单里的位置标记，例如「第 3 页」",
      "title": "这一页的标题（取自清单）",
      "transcript": "老师讲这一页时说的话，原文照抄（可去掉口头语）。这一页没讲到就填空字符串",
      "start": 起始秒数（数字，没有就填 0）,
      "end": 结束秒数（数字，没有就填 0）,
      "aiFilled": false 或 true（true 表示这页录像里没讲到）,
      "keyPoints": ["这一段里老师强调的要点，2-4 条"],
      "askClass": "老师在这一段里提的问题（没有就填空字符串）",
      "transition": "过渡到下一页的一句话（没有就填空字符串）"
    }
  ]
}

要求：
- segments 必须**覆盖清单里的每一页**，一页都不能少，顺序不能乱。
- transcript 字段是「老师原话」，不是你的总结。这一点最重要。
- 不要把两页的内容混在一起，也不要把 A 页的话放到 B 页。`;
}

